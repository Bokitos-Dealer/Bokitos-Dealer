def mrr_params(poly):
    mrr = poly.minimum_rotated_rectangle
    cs = list(mrr.exterior.coords)[:4]
    e1 = (cs[1][0] - cs[0][0], cs[1][1] - cs[0][1])
    e2 = (cs[2][0] - cs[1][0], cs[2][1] - cs[1][1])
    c = mrr.centroid
    return (c.x, c.y, math.hypot(*e1), math.hypot(*e2), math.atan2(e1[1], e1[0]))


def is_corner(ring, flags, facade):
    """Does the building also face a street at an angle (a corner house)?"""
    n = len(ring)
    a, c = ring[facade], ring[(facade + 1) % n]
    fa = math.atan2(c[1] - a[1], c[0] - a[0])
    for vi, f in enumerate(flags):
        if f >= 2 and vi != facade:
            p, q = ring[vi], ring[(vi + 1) % n]
            if math.dist(p, q) < 2.5:
                continue
            d = abs((math.atan2(q[1] - p[1], q[0] - p[0]) - fa + math.pi) % (2 * math.pi) - math.pi)
            if d > math.radians(12):
                return True
    return False


def multi_facade_boxes(poly, ring, flags):
    """Corner houses: one box behind each street front (fronts that line up
    are joined). Boxes may not stick out of the footprint."""
    n = len(ring)
    spans = []  # (start vertex, end vertex)
    for vi in range(n):
        if flags[vi] < 2:
            continue
        a, c = ring[vi], ring[(vi + 1) % n]
        if spans and spans[-1][1] == vi:
            s0 = ring[spans[-1][0]]
            d1 = math.atan2(c[1] - a[1], c[0] - a[0])
            d0 = math.atan2(a[1] - s0[1], a[0] - s0[0])
            if abs((d1 - d0 + math.pi) % (2 * math.pi) - math.pi) < math.radians(8):
                spans[-1] = (spans[-1][0], (vi + 1) % n)
                continue
        spans.append((vi, (vi + 1) % n))
    spans = [sp for sp in spans if math.dist(ring[sp[0]], ring[sp[1]]) >= 2.5]
    if not spans or len(spans) > 5:
        return None
    fence = poly.buffer(0.6, join_style="mitre")
    out, shapes = [], []
    for i0, i1 in spans:
        a, c = ring[i0], ring[i1]
        L = math.dist(a, c)
        ux, uy = (c[0] - a[0]) / L, (c[1] - a[1]) / L
        ix, iy = -uy, ux
        dmax = max((p[0] - a[0]) * ix + (p[1] - a[1]) * iy for p in ring)
        placed = False
        for depth in (dmax, dmax * 0.75, dmax * 0.55, dmax * 0.4, 9.0, 6.0, 4.0):
            if depth < 2.5 or depth > dmax + 0.01:
                continue
            quad = Polygon([a, c, (c[0] + ix * depth, c[1] + iy * depth), (a[0] + ix * depth, a[1] + iy * depth)])
            if fence.contains(quad):
                out.append((a[0] + ux * L / 2 + ix * depth / 2, a[1] + uy * L / 2 + iy * depth / 2, L, depth, math.atan2(uy, ux)))
                shapes.append(quad)
                placed = True
                break
        if not placed:
            return None
    if unary_union(shapes).area < 0.6 * poly.area:
        return None
    return out


def facade_box(poly, ring, vi):
    """A box lined up with the street front, as deep as the building.
    The front is exact; small differences hide at the back."""
    n = len(ring)
    a, c = ring[vi], ring[(vi + 1) % n]
    L = math.dist(a, c)
    if L < 2:
        return None
    ux, uy = (c[0] - a[0]) / L, (c[1] - a[1]) / L
    ix, iy = -uy, ux  # inward normal (rings are counter-clockwise)
    ss, ts = [], []
    for p in ring:
        dx, dy = p[0] - a[0], p[1] - a[1]
        ss.append(dx * ux + dy * uy)
        ts.append(dx * ix + dy * iy)
    depth = max(ts)
    if depth < 2 or depth > 70 or min(ts) < -0.6:
        return None
    if L * depth > 2.2 * poly.area or L * depth < 0.6 * poly.area:
        return None
    cx = a[0] + ux * L / 2 + ix * depth / 2
    cy = a[1] + uy * L / 2 + iy * depth / 2
    return [(cx, cy, L, depth, math.atan2(uy, ux))]


def solid_rects(poly):
    """Boxes that fill the footprint, or None if triangles are better."""
    cx, cy, w, d, th = mrr_params(poly)
    if not poly.interiors and w * d <= poly.area * 1.05:
        return [(cx, cy, w, d, th)]
    rects = ortho_rects(poly)
    if rects is None:
        return None
    n_verts = len(poly.exterior.coords) - 1 + sum(len(r.coords) - 1 for r in poly.interiors)
    wedges = 2 * (n_verts - 2 + 2 * len(poly.interiors))
    return rects if len(rects) <= max(2, wedges) else None


def ortho_rects(poly, tol=math.radians(5)):
    """Split an (almost) right-angled footprint into boxes."""
    ring = list(poly.exterior.coords)
    best, ang = 0, 0
    for a, b in zip(ring, ring[1:]):
        L = math.dist(a, b)
        if L > best:
            best, ang = L, math.atan2(b[1] - a[1], b[0] - a[0])
    for r in [poly.exterior] + list(poly.interiors):
        cs = list(r.coords)
        for a, b in zip(cs, cs[1:]):
            if math.dist(a, b) < 0.8:
                continue
            t = (math.atan2(b[1] - a[1], b[0] - a[0]) - ang) % (math.pi / 2)
            if min(t, math.pi / 2 - t) > tol:
                return None
    from shapely import affinity
    rp = affinity.rotate(poly, -ang, origin=(0, 0), use_radians=True)
    minx, miny, maxx, maxy = rp.bounds
    xs = sorted(set(round(x, 1) for r in [rp.exterior] + list(rp.interiors) for x, _ in r.coords))
    clean = []
    for x in xs:
        if not clean or x - clean[-1] > 0.25:
            clean.append(x)
    clean[0], clean[-1] = minx, maxx
    rects, openr = [], {}
    for i in range(len(clean) - 1):
        x0, x1 = clean[i], clean[i + 1]
        if x1 - x0 < 0.05:
            continue
        strip = rp.intersection(box(x0, miny - 1, x1, maxy + 1))
        ivs = set()
        for q in polys_of(strip):
            if q.area > 0.05:
                b = q.bounds
                ivs.add((round(b[1] * 4) / 4, round(b[3] * 4) / 4))
        nxt = {}
        for iv in ivs:
            if iv in openr:
                nxt[iv] = [openr[iv][0], x1]
            else:
                nxt[iv] = [x0, x1]
        for iv, span in openr.items():
            if iv not in nxt:
                rects.append((span, iv))
        openr = nxt
    for iv, span in openr.items():
        rects.append((span, iv))
    out = []
    c, s = math.cos(ang), math.sin(ang)
    for (x0, x1), (y0, y1) in rects:
        mx, my = (x0 + x1) / 2, (y0 + y1) / 2
        out.append((mx * c - my * s, mx * s + my * c, x1 - x0, y1 - y0, ang))
    return out


def weighted(rng, items):
    total = sum(w for w, *_ in items)
    r = rng.random() * total
    for w, col, mat in items:
        r -= w
        if r <= 0:
            return col, mat
    return items[-1][1], items[-1][2]


def is_rect(ring):
    if len(ring) != 4:
        return False
    for i in range(4):
        a, b, c = ring[i - 1], ring[i], ring[(i + 1) % 4]
        v1 = (a[0] - b[0], a[1] - b[1])
        v2 = (c[0] - b[0], c[1] - b[1])
        l1, l2 = math.hypot(*v1), math.hypot(*v2)
        if l1 < 0.5 or l2 < 0.5:
            return False
        if abs((v1[0] * v2[0] + v1[1] * v2[1]) / (l1 * l2)) > 0.035:
            return False
    return True


def game_yaw(math_angle):
    """Direction in map maths (x east, y north) -> Roblox yaw where a part's
    local -Z (its front) points along the direction."""
    dx, dy = math.cos(math_angle), math.sin(math_angle)
    # world x = dx, world z = -dy; front -Z = (-sin yaw, -cos yaw)
    return math.atan2(-dx, dy)


