        # lanes: kind width flags j0 j1 y n points
        lane_codes = {"car": 1, "bike": 2, "walk": 3, "boat": 4, "tram": 5}
        lw = Writer()
        for kind, width, flags, j0, j1, line, y in self.lanes:
            c = list(line.coords)
            rec = [lane_codes[kind], self.dm(width), flags, j0, j1, self.dm(y) if y > -90 else -999, len(c)]
