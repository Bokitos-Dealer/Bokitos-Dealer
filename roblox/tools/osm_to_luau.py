def colour(v):
    if not v:
        return None
    v = v.strip().lower()
    if re.match(r"^#[0-9a-f]{6}$", v):
        return int(v[1:], 16)
    if re.match(r"^#[0-9a-f]{3}$", v):
        return int("".join(c * 2 for c in v[1:]), 16)
    return NAMED_COLOURS.get(v.replace(" ", "").replace("_", ""))


def polys_of(g):
    if g is None or g.is_empty:
        return []
    if isinstance(g, Polygon):
        return [g]
    if isinstance(g, (MultiPolygon, GeometryCollection)):
        out = []
        for x in g.geoms:
            out += polys_of(x)
        return out
    return []


def lines_of(g):
    if g is None or g.is_empty:
        return []
    if isinstance(g, LineString):
        return [g]
    if isinstance(g, (MultiLineString, GeometryCollection)):
        out = []
        for x in g.geoms:
            out += lines_of(x)
        return out
    return []


class Writer:
    """Collects integer records and writes them as Luau string modules."""

    def __init__(self):
        self.lines = []

    def add(self, ints):
        self.lines.append(" ".join(v if isinstance(v, str) else str(int(round(v))) for v in ints))

    def modules(self, limit=150_000):
        chunks, cur, size = [], [], 0
        for line in self.lines:
            if size + len(line) > limit and cur:
                chunks.append("\n".join(cur))
                cur, size = [], 0
            cur.append(line)
            size += len(line) + 1
        if cur:
            chunks.append("\n".join(cur))
        return chunks


def luau_string_module(text, comment):
    return "-- " + comment + "\n-- Map data (c) OpenStreetMap contributors, ODbL. Generated by tools/osm_to_luau.py.\nreturn [==[\n" + text + "\n]==]\n"


