class City:
    def __init__(self, key, cfg, osm_dir):
        self.key = key
        self.cfg = cfg
        self.o = OSM().load_dir(os.path.join(osm_dir, key))
        x0, y0, x1, y1 = cfg["bbox"]
        self.lat0 = (y0 + y1) / 2
        self.lon0 = (x0 + x1) / 2
        self.kx = math.cos(math.radians(self.lat0)) * 111320.0
        self.ky = 110540.0
        ax0, ay0 = self.ll(y0, x0)
        ax1, ay1 = self.ll(y1, x1)
        m = 12.0
        self.area = box(ax0 + m, ay0 + m, ax1 - m, ay1 - m)
        self.boundary = self.area.exterior
        self.stats = defaultdict(int)

    # lat/lon -> local metres (x east, y north)
    def ll(self, lat, lon):
        return ((lon - self.lon0) * self.kx, (lat - self.lat0) * self.ky)

    def node_xy(self, n):
        la, lo, _ = self.o.nodes[n]
        return self.ll(la, lo)

    def way_coords(self, wid):
        w = self.o.ways.get(wid)
        if not w:
            return None
        nds = w[0]
        if any(n not in self.o.nodes for n in nds):
            return None
        return [self.node_xy(n) for n in nds]

    @staticmethod
    def dm(v):
        return int(round(v * 10))

    def xz(self, x, y):
        """metres (x east, y north) -> (x, z) decimetres."""
        return self.dm(x), self.dm(-y)

    # -- polygons --------------------------------------------------------------
    def way_polygon(self, wid):
        c = self.way_coords(wid)
        if not c or len(c) < 4 or c[0] != c[-1]:
            return None
        p = Polygon(c)
        if not p.is_valid:
            p = p.buffer(0)
        return p if not p.is_empty else None

    def rel_polygon(self, rid, allow_open=False, inside_test=None):
        members, _ = self.o.rels[rid]
        outer, inner, missing = [], [], False
        for t, ref, role in members:
            if t != "way":
                continue
            c = self.way_coords(ref)
            if not c:
                missing = True
                continue
            (inner if role == "inner" else outer).append(LineString(c))
        if not outer:
            return None

        def rings(lines):
            if not lines:
                return [], []
            merged = linemerge(lines)
            parts = lines_of(merged)
            closed = [l for l in parts if l.is_ring and len(l.coords) >= 4]
            opened = [l for l in parts if not (l.is_ring and len(l.coords) >= 4)]
            return closed, opened

        oc, oo = rings(outer)
        ic, _ = rings(inner)
        polys = [Polygon(r).buffer(0) for r in oc]
        if oo and allow_open and inside_test is not None:
            # incomplete relation (cut by our download area): close it with
            # the area boundary and keep the faces that contain water lines
            faces = polygonize(unary_union(oo + [self.boundary]))
            for f in faces:
                if inside_test(f):
                    polys.append(f)
        if not polys:
            return None
        g = unary_union(polys)
        if ic:
            g = g.difference(unary_union([Polygon(r).buffer(0) for r in ic]))
        return g if not g.is_empty else None

    def area_features(self, match, allow_open=False, inside_test=None):
        """[(geometry, tags, osm id)] for closed ways and multipolygons."""
        out = []
        for wid, (nds, tags) in self.o.ways.items():
            if match(tags) and nds and nds[0] == nds[-1]:
                p = self.way_polygon(wid)
                if p is not None:
                    out.append((p, tags, wid))
        for rid, (members, tags) in self.o.rels.items():
            if tags.get("type") == "multipolygon" and match(tags):
                p = self.rel_polygon(rid, allow_open, inside_test)
                if p is not None:
                    out.append((p, tags, -rid))
        return out

    # ---------------------------------------------------------------------------
    def run(self):
        cfg = self.cfg
        self.collect_roads()
        self.collect_water()
        self.collect_buildings()
        self.collect_props()
        self.collect_lanes()
        self.pick_spots()
        self.write()

    # -- roads -------------------------------------------------------------------
    CAR = {"motorway": 14, "trunk": 14, "primary": 13, "secondary": 11, "tertiary": 9,
           "unclassified": 6.5, "residential": 6.5, "living_street": 5, "service": 4.5,
           "busway": 6, "primary_link": 7, "secondary_link": 7, "tertiary_link": 6,
           "motorway_link": 7, "trunk_link": 7, "road": 6}

    def road_kind(self, tags):
        hw = tags.get("highway")
        if not hw:
            return None
        if tags.get("tunnel") in ("yes", "building_passage", "culvert") or tags.get("location") == "underground":
            return None
        try:
            if int(tags.get("layer", "0").split(";")[0]) < 0:
                return None
        except ValueError:
            pass
        if tags.get("indoor") == "yes" or tags.get("area") == "yes":
            return None
        if hw in self.CAR:
            if hw == "service" and tags.get("service") in ("parking_aisle", "drive-through"):
                return None
            return "car"
        if hw == "cycleway":
            return "bike"
        if hw == "pedestrian":
            return "ped"
        if hw in ("footway", "path", "track", "bridleway"):
            if tags.get("footway") in ("sidewalk", "crossing", "traffic_island") and tags.get("bridge") != "yes":
                return "sidewalk"
            return "path"
        return None

    def road_width(self, kind, tags):
        w = num(tags.get("width"))
        hw = tags.get("highway")
        if kind == "car":
            lanes = num(tags.get("lanes"))
            base = self.CAR.get(hw, 6)
            if lanes and lanes >= 1:
                base = max(base * 0.6, min(lanes * 3.3, 36))
            if w and 3 <= w <= 40:
                base = w
            return base
        if kind == "bike":
            return w if w and 1.5 <= w <= 6 else 2.6
        if kind == "ped":
            return w if w and 2 <= w <= 30 else 7
        return w if w and 1 <= w <= 8 else 2.4

    SURF = {"asphalt": 0, "paving_stones": 1, "sett": 2, "cobblestone": 2, "unhewn_cobblestone": 2,
            "bricks": 1, "brick": 1, "concrete": 4, "concrete:plates": 4, "fine_gravel": 6, "gravel": 6,
            "compacted": 6, "dirt": 6, "ground": 6, "unpaved": 6, "sand": 6, "grass": 9, "wood": 7,
            "metal": 4, "paved": 0, "granite": 8, "stone": 2}

    def road_surface(self, kind, tags):
        s = tags.get("surface")
        code = self.SURF.get(s, None)
        style = self.cfg["style"]
        if code is None:
            if kind == "bike":
                code = 3 if style == "amsterdam" else 0
            elif kind == "ped":
                code = 5
            elif kind == "path":
                code = 6 if style == "paris" else 5
            else:
                code = 0
        if kind == "bike" and code == 0 and style == "amsterdam":
            code = 3  # Dutch bike paths are red asphalt
        if kind == "ped" and code == 1:
            code = 5
        if code == 1 and style != "amsterdam":
            code = 5
        return code

    def collect_roads(self):
        self.roads = []  # dict(kind, width, surf, flags, line (metres), tags, id)
        bridge_areas = [p for p, t, i in self.area_features(lambda t: t.get("man_made") == "bridge")]
        self.bridge_areas = [g for p in bridge_areas for g in polys_of(p.intersection(self.area))]
        bu = unary_union(self.bridge_areas) if self.bridge_areas else None
        for wid, (nds, tags) in self.o.ways.items():
            kind = self.road_kind(tags)
            if not kind:
                continue
            c = self.way_coords(wid)
            if not c or len(c) < 2:
                continue
            line = LineString(c)
            width = self.road_width(kind, tags)
            surf = self.road_surface(kind, tags)
            flags = 0
            is_bridge = tags.get("bridge") not in (None, "no")
            if is_bridge:
                flags |= 1
                if bu is not None and line.length > 0:
                    inside = line.intersection(bu).length / line.length
                    if inside > 0.6:
                        flags |= 8  # the bridge already has a deck polygon
            if tags.get("oneway") in ("yes", "1", "true"):
                flags |= 2
            if kind == "car" and (tags.get("cycleway") in ("lane", "track") or tags.get("cycleway:both") == "lane"
                                  or tags.get("cycleway:right") == "lane" or tags.get("cycleway:left") == "lane"):
                flags |= 32
            hw = tags.get("highway")
            if kind == "car" and hw in ("primary", "secondary", "tertiary", "trunk") and (num(tags.get("lanes")) or 2) >= 2:
                flags |= 64
            for part in lines_of(line.intersection(self.area)):
                part = part.simplify(0.3)
                if part.length < 1:
                    continue
                self.roads.append(dict(kind=kind, width=width, surf=surf, flags=flags, line=part, tags=tags, id=wid))
        self.stats["roads"] = len(self.roads)
        # tram rails
        self.trams = []
        for wid, (nds, tags) in self.o.ways.items():
            if tags.get("railway") == "tram" and tags.get("tunnel") != "yes":
                c = self.way_coords(wid)
                if c and len(c) >= 2:
                    for part in lines_of(LineString(c).intersection(self.area)):
                        if part.length > 2:
                            self.trams.append(dict(line=part.simplify(0.2), bridge=tags.get("bridge") not in (None, "no")))
        # index for "is this near a street?"
        street_lines = [r["line"] for r in self.roads if r["kind"] in ("car", "bike", "ped", "path")]
        self.street_tree = STRtree(street_lines) if street_lines else None
        self.car_roads = [r for r in self.roads if r["kind"] == "car"]
        self.car_tree = STRtree([r["line"] for r in self.car_roads]) if self.car_roads else None

    # -- water, grass, bridges, piers -------------------------------------------------
    def collect_water(self):
        cfg = self.cfg
        lines = []
        for wid, (nds, tags) in self.o.ways.items():
            if tags.get("waterway") in ("river", "canal"):
                c = self.way_coords(wid)
                if c and len(c) >= 2:
                    lines.append(LineString(c))
        river_lines = unary_union(lines) if lines else None

        def has_river(face):
            return river_lines is not None and face.intersects(river_lines) and face.area > 200

        feats = self.area_features(lambda t: (t.get("natural") == "water" or t.get("waterway") in ("riverbank", "dock")
                                              or t.get("landuse") in ("basin", "reservoir")) and t.get("tunnel") != "yes"
                                   and t.get("covered") != "yes", allow_open=True, inside_test=has_river)
        water = unary_union([f[0] for f in feats]) if feats else None
        self.water = [p for p in polys_of(water.intersection(self.area).buffer(0))] if water else []
        self.water = [p.simplify(0.4) for p in self.water if p.area > 8]
        self.water_union = unary_union(self.water) if self.water else None
        self.stats["water polys"] = len(self.water)
        self.river_lines = lines

        def is_green(t):
            return (t.get("leisure") in ("park", "garden", "playground", "dog_park", "common")
                    or t.get("landuse") in ("grass", "village_green", "meadow", "forest", "flowerbed", "recreation_ground", "cemetery")
                    or t.get("natural") in ("grassland", "scrub", "wood", "heath"))
        green = []
        for g, t, i in self.area_features(is_green):
            kind = 3 if (t.get("landuse") == "forest" or t.get("natural") in ("wood", "scrub")) else 2
            if t.get("leisure") == "playground":
                kind = 4
            if t.get("landuse") == "flowerbed":
                kind = 5
            for p in polys_of(g.intersection(self.area).buffer(0)):
                p = p.simplify(0.5)
                if p.area > 15:
                    if self.water_union is not None:
                        p2 = p.difference(self.water_union)
                        for q in polys_of(p2):
                            if q.area > 15:
                                green.append((kind, q))
                    else:
                        green.append((kind, p))
        # big parks are listed first so small flowerbeds paint on top
        green.sort(key=lambda kp: -kp[1].area)
        self.green = green
        self.stats["green polys"] = len(green)
        piers = []
        for g, t, i in self.area_features(lambda t: t.get("man_made") == "pier"):
            for p in polys_of(g.intersection(self.area)):
                if p.area > 4:
                    piers.append(p.simplify(0.3))
        self.piers = piers
        # pedestrian squares (Dam, Times Square...) are drawn as paving
        squares = []
        for g, t, i in self.area_features(lambda t: (t.get("highway") == "pedestrian" and t.get("area") == "yes")
                                          or t.get("area:highway") in ("pedestrian", "footway")
                                          or t.get("place") == "square"):
            for p in polys_of(g.intersection(self.area).buffer(0)):
                if p.area > 30:
                    squares.append(p.simplify(0.4))
        self.squares = squares

    # -- buildings ------------------------------------------------------------------------
    def collect_buildings(self):
        cfg = self.cfg
        style = cfg["style"]
        excl = [(Point(*self.ll(la, lo)), r) for (la, lo, r) in cfg.get("exclude", [])]

        def excluded(p):
            c = p.representative_point()
            return any(c.distance(pt) < r for pt, r in excl)

        def skip(t):
            b = t.get("building") or t.get("building:part")
            return (b in ("no", "construction", "ruins", "collapsed", "demolished", "proposed")
                    or t.get("location") == "underground" or t.get("layer", "0").startswith("-"))

        outlines = [f for f in self.area_features(lambda t: "building" in t and not skip(t)) if not excluded(f[0])]
        parts = [f for f in self.area_features(lambda t: "building:part" in t and "building" not in t and not skip(t)
                                                and t.get("building:part") not in ("no",)) if not excluded(f[0])]
        level_h = cfg["level_h"]

        def heights(t, parent=None):
            h = num(t.get("height"))
            levels = num(t.get("building:levels"))
            roof_levels = num(t.get("roof:levels")) or 0
            if h is None and levels is not None:
                h = levels * level_h + roof_levels * 2.6 + cfg.get("roof_extra", 0)
            if h is None and parent is not None:
                h = parent[0]
            if h is None:
                b = t.get("building", "yes")
                if b == "houseboat":
                    h = 3.2
                elif b in ("roof", "carport"):
                    h = 4
                elif b in ("shed", "garage", "kiosk", "hut", "cabin"):
                    h = 3.5
                else:
                    h = cfg["default_h"]
            mh = num(t.get("min_height"))
            if mh is None:
                ml = num(t.get("building:min_level"))
                mh = ml * level_h if ml else 0.0
            if t.get("building") in ("roof", "carport") and mh == 0:
                mh = max(0, h - 1.0)
            h = max(h, mh + 1.0)
            return min(h, 600), max(0, mh)

        out_geoms = [g for g, t, i in outlines]
        tree = STRtree(out_geoms) if out_geoms else None
        part_of = defaultdict(list)
        for k, (g, t, i) in enumerate(parts):
            if tree is None:
                continue
            idx = tree.query(g.representative_point(), predicate="intersects")
            if len(idx):
                part_of[int(idx[0])].append(k)
        solids = []  # (geom, h, mh, tags, id, kind)
        for k, (g, t, i) in enumerate(outlines):
            h, mh = heights(t)
            ps = part_of.get(k, [])
            if ps:
                cover = unary_union([parts[j][0] for j in ps]).area
                if cover >= 0.5 * g.area:
                    for j in ps:
                        pg, pt, pid = parts[j]
                        merged = dict(t)
                        merged.update(pt)
                        ph, pmh = heights(pt, (h, mh))
                        solids.append((pg, ph, pmh, merged, pid, "part"))
                    continue
            solids.append((g, h, mh, t, i, "building"))
        # parts with no outline at all
        claimed = {j for v in part_of.values() for j in v}
        for j, (g, t, i) in enumerate(parts):
            if j not in claimed and num(t.get("height")):
                h, mh = heights(t)
                solids.append((g, h, mh, t, i, "part"))
        # clip, simplify, orient
        final = []
        for g, h, mh, t, i, kind in solids:
            for p in polys_of(g.intersection(self.area)):
                p = p.simplify(0.35, preserve_topology=True)
                p = p.buffer(0) if not p.is_valid else p
                for q in polys_of(p):
                    if q.area < 5:
                        continue
                    # courtyards can't be seen from the street: fill them in
                    q = orient(Polygon(q.exterior), 1.0)
                    final.append(dict(geom=q, h=h, mh=mh, tags=t, id=i, kind=kind))
        # buildings deep inside a block can't be seen from the street: skip them
        open_geoms = [r["line"] for r in self.roads] + [w.exterior for w in self.water] + list(self.squares)
        if open_geoms and final:
            otree = STRtree(open_geoms)
            pi, gi = otree.query([b["geom"] for b in final], predicate="dwithin", distance=10.0)
            near = set(int(a) for a in pi)
            keep = []
            for i, b in enumerate(final):
                if i in near or b["h"] > 30:
                    keep.append(b)
            self.stats["hidden buildings skipped"] = len(final) - len(keep)
            final = keep
        # irregular footprints need triangles: simplify them a bit more
        for b in final:
            g = b["geom"]
            if len(g.exterior.coords) > 7 and solid_rects(g) is None:
                g2 = g.simplify(self.cfg.get("rough_simplify", 0.6), preserve_topology=True)
                if g2.is_valid and not g2.is_empty and isinstance(g2, Polygon) and g2.area > 0.9 * g.area:
                    b["geom"] = orient(g2, 1.0)
        self.buildings = final
        self.stats["buildings"] = len(final)
        self.classify_edges()

    def classify_edges(self):
        cfg = self.cfg
        bl = self.buildings
        tree = STRtree([b["geom"] for b in bl])
        shops = []
        for n, (la, lo, t) in self.o.nodes.items():
            if "shop" in t or t.get("amenity") in ("cafe", "restaurant", "fast_food", "ice_cream", "bar", "pub", "bank", "pharmacy"):
                shops.append(Point(*self.ll(la, lo)))
        shop_tree = STRtree(shops) if shops else None
        open_roads = [r for r in self.roads if r["kind"] in ("car", "bike", "ped", "path", "sidewalk")]
        open_tree_geoms = [r["line"] for r in open_roads]
        open_half = [r["width"] / 2 for r in open_roads]
        if self.water_union is not None:
            open_tree_geoms += [w.exterior for w in self.water]
            open_half += [0.0] * len(self.water)
        open_tree_geoms += [s for s in self.squares]
        open_half += [0.0] * len(self.squares)
        open_tree = STRtree(open_tree_geoms) if open_tree_geoms else None
        # gather every edge
        edges = []  # (building index, ring index, vertex index, mid, normal, length)
        for bi, b in enumerate(bl):
            rings = [list(b["geom"].exterior.coords)[:-1]] + [list(r.coords)[:-1] for r in b["geom"].interiors]
            b["rings"] = rings
            b["flags"] = [[0] * len(r) for r in rings]
            for ri, ring in enumerate(rings):
                n = len(ring)
                for vi in range(n):
                    a = ring[vi]
                    c = ring[(vi + 1) % n]
                    dx, dy = c[0] - a[0], c[1] - a[1]
                    L = math.hypot(dx, dy)
                    if L < 0.3:
                        continue
                    nx, ny = dy / L, -dx / L
                    edges.append((bi, ri, vi, ((a[0] + c[0]) / 2, (a[1] + c[1]) / 2), (nx, ny), L))
        if not edges:
            return
        mids = np.array([e[3] for e in edges])
        nrm = np.array([e[4] for e in edges])
        q1 = shapely.points(mids + nrm * 0.6)
        q2 = shapely.points(mids + nrm * 4.0)
        cover = defaultdict(list)
        pi, gi = tree.query(q1, predicate="intersects")
        for a, b in zip(pi, gi):
            cover[int(a)].append(int(b))
        near2 = set()
        pi, gi = tree.query(q2, predicate="intersects")
        for a, b in zip(pi, gi):
            if bl[int(b)]["h"] > 3:
                near2.add(int(a))
        street = set()
        if open_tree is not None:
            pts = shapely.points(mids)
            (pi, gi), dist = open_tree.query_nearest(pts, max_distance=60.0, return_distance=True)
            # a facade faces the street when the street edge is close by
            street = set(int(a) for a, g, d in zip(pi, gi, dist) if d - open_half[int(g)] <= 13.0)
        shopfront = set()
        if shop_tree is not None:
            pts = shapely.points(mids)
            pi, gi = shop_tree.query_nearest(pts, max_distance=7.0, return_distance=False)
            shopfront = set(int(a) for a in pi)
        counts = defaultdict(int)
        for k, (bi, ri, vi, mid, n, L) in enumerate(edges):
            b = bl[bi]
            flag = 1
            top = -1
            for oj in cover.get(k, []):
                if oj == bi:
                    continue
                o = bl[oj]
                if o["mh"] <= b["mh"] + 1.0:
                    top = max(top, o["h"])
            if top >= b["h"] - 0.8:
                flag = 0
            elif top < 0 and k not in near2 and k in street and ri == 0:
                flag = 3 if (k in shopfront and b["mh"] < 1) else 2
            b["flags"][ri][vi] = flag
            counts[flag] += 1
        self.stats["edges hidden/blank/street/shop"] = "%d/%d/%d/%d" % (counts[0], counts[1], counts[2], counts[3])

    # -- props ------------------------------------------------------------------------------
    def nearest_road_dir(self, x, y, kinds=("car",)):
        """direction (radians, math coords) and distance of the nearest road line."""
        tree, roads = self.car_tree, self.car_roads
        if tree is None:
            return 0.0, 1e9, None
        p = Point(x, y)
        idx = tree.query_nearest(p)
        if not len(idx):
            return 0.0, 1e9, None
        r = roads[int(idx[0])]
        line = r["line"]
        s = line.project(p)
        a = line.interpolate(max(0, s - 1))
        b = line.interpolate(min(line.length, s + 1))
        return math.atan2(b.y - a.y, b.x - a.x), line.distance(p), r

    def collect_props(self):
        cfg = self.cfg
        props = []  # (type, x, y, angle radians math, extra)
        inside = self.area.contains
        rng = stable_rng(self.key, "props")
        lamp_light = 0
        for n, (la, lo, t) in self.o.nodes.items():
            x, y = self.ll(la, lo)
            if not inside(Point(x, y)):
                continue
            if t.get("natural") == "tree":
                hgt = num(t.get("height"))
                props.append((1, x, y, 0, int((hgt or 0) * 10)))
            elif t.get("highway") == "street_lamp":
                lamp_light += 1
                props.append((2, x, y, 0, 1 if lamp_light % cfg.get("light_every", 2) == 0 else 0))
            elif t.get("amenity") == "bench":
                ang, d, _ = self.nearest_road_dir(x, y)
                props.append((3, x, y, ang, 0))
            elif t.get("amenity") == "bicycle_parking":
                ang, d, _ = self.nearest_road_dir(x, y)
                cap = int(num(t.get("capacity")) or 4)
                props.append((4, x, y, ang, max(2, min(cap, 6))))
            elif t.get("barrier") == "bollard":
                props.append((5, x, y, 0, 0))
            elif t.get("amenity") == "fountain":
                props.append((6, x, y, 0, 0))
            elif t.get("highway") == "traffic_signals":
                ang, d, r = self.nearest_road_dir(x, y)
                if r is not None and d < 12:
                    props.append((7, x, y, ang, int(r["width"] * 10)))
            elif t.get("advertising") == "column":
                props.append((8, x, y, 0, 0))
            elif t.get("emergency") == "fire_hydrant":
                props.append((9, x, y, 0, 0))
            elif t.get("highway") == "bus_stop" and t.get("shelter") == "yes":
                ang, d, _ = self.nearest_road_dir(x, y)
                props.append((10, x, y, ang, 0))
            elif t.get("highway") == "crossing" and (t.get("crossing") in ("zebra", "marked", "uncontrolled", "traffic_signals")
                                                     or t.get("crossing:markings") in ("yes", "zebra", "ladder", "lines")):
                ang, d, r = self.nearest_road_dir(x, y)
                if r is not None and d < 3 and r["tags"].get("highway") not in ("service",):
                    props.append((11, x, y, ang, int(r["width"] * 10)))
        # thin out the very dense layers (keeps the city smooth on phones)
        caps = cfg.get("prop_caps", {})
        by_type = defaultdict(list)
        for p in props:
            by_type[p[0]].append(p)
        final = []
        for ty, lst in by_type.items():
            cap = caps.get(ty)
            if cap and len(lst) > cap:
                rng.shuffle(lst)
                lst = lst[:cap]
            final += lst
        self.props = final
        cnt = defaultdict(int)
        for p in final:
            cnt[p[0]] += 1
        self.stats["props"] = dict(cnt)

