# helpers
def num(v):
    """'12.5', '12 m', '40 ft', '3;4' -> metres (float) or None."""
    if v is None:
        return None
    v = v.split(";")[0].strip().replace(",", ".")
    m = re.match(r"^(-?\d+(?:\.\d+)?)\s*(m|ft|')?", v)
    if not m:
        return None
    x = float(m.group(1))
    if m.group(2) in ("ft", "'"):
        x *= 0.3048
    return x


def stable_rng(*keys):
    h = zlib.crc32(("|".join(str(k) for k in keys)).encode())
    return random.Random(h)


